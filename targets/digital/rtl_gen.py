"""Parameterized LIF fabric RTL generator.

Protocol (one timestep = inject cycles + 1 update cycle + emission cycles):
- Host drives inject_valid=1 with inject_addr = source index s and
  inject_data = spike bit (0/1), once per source per timestep, any order.
- A cycle with inject_valid=0 (after at least one inject) closes the timestep:
  neurons integrate v' = (decay*v >>> shift) + accumulated current - leak,
  fire when v' >= THR, reset fired neurons to REST.
- Fires stream out one per cycle on spike_out_* until none remain.

Weights: dense column-major ROM, one word per source (PAD entries of WW
signed bits), emitted from the same seeded integer weights as the golden
model (T2->T4): word[s][i] = w_int[i][s].

ponytail: dense N×N ROM — fine to ~1k neurons (~1 Mb); switch to sparse
fanout rows + reverse index if configs exceed that.
"""

import numpy as np

from targets.digital.model import sample_weight_ints


def _next_pow2(n: int) -> int:
    p = 2
    while p < n:
        p *= 2
    return p


def module_name(cfg: dict) -> str:
    return f"snn_core_{cfg['neurons']}"


def pad_size(cfg: dict) -> int:
    return _next_pow2(max(int(cfg["neurons"]), 2))


def generate_rtl(cfg: dict) -> str:
    n = int(cfg["neurons"])
    ww = int(cfg["weight_width"])
    p = pad_size(cfg)
    acc_w = ww + p.bit_length() + 4  # signed headroom for decayed+acc
    thr = int(round(float(cfg.get("threshold", 1.0)) * 2**ww))
    rest = int(round(float(cfg.get("rest", 0.0)) * 2**ww))
    leak = int(round(float(cfg.get("leak", 0.0)) * 2**ww))

    w_int = sample_weight_ints(cfg)
    w_full = np.zeros((p, p), dtype=np.int64)
    w_full[:n, :n] = w_int
    mask = 2**ww - 1
    rom_words = [
        sum((int(w_full[i, s]) & mask) << (i * ww) for i in range(p))
        for s in range(p)
    ]

    L: list[str] = []
    a = L.append
    a(f"// generated by rtl_gen.py; neurons={n} fanout={cfg.get('fanout')} ww={ww} seed={cfg.get('seed', 1)}")
    a("`timescale 1ns/1ps")
    a(f"module {module_name(cfg)} (")
    a("    input  wire        clk,")
    a("    input  wire        rst_n,")
    a("    input  wire        inject_valid,")
    a("    input  wire [15:0] inject_addr,")
    a("    input  wire        inject_data,")
    a("    output reg         spike_out_valid,")
    a("    output reg  [15:0] spike_out_addr,")
    a("    output reg         spike_out_data")
    a(");")
    a(f"localparam N = {n};")
    a(f"localparam PAD = {p};")
    a(f"localparam WW = {ww};")
    a(f"localparam ACC_W = {acc_w};")
    a(f"localparam signed ACC_W_THR = {acc_w}'sd{thr};")
    a(f"localparam signed ACC_W_REST = {acc_w}'sd{rest};")
    a(f"localparam signed ACC_W_LEAK = {acc_w}'sd{leak};")
    a("localparam signed DECAY_NUM = 14;")
    a("localparam DECAY_SHIFT = 4;")
    a("localparam PH_IDLE = 2'd0, PH_INJECT = 2'd1, PH_UPDATE = 2'd2, PH_EMIT = 2'd3;")
    a("")
    a("reg [1:0] phase;")
    a(f"reg signed [ACC_W-1:0] v [0:PAD-1];")
    a(f"reg signed [ACC_W-1:0] acc [0:PAD-1];")
    a(f"reg [PAD-1:0] fire_shift;")
    a(f"reg [PAD*WW-1:0] col;")
    a("reg col_bit;")
    a("")
    a("// decayed membrane, 32-bit intermediate, no truncation before compare")
    a("wire signed [31:0] decayed [0:PAD-1];")
    a("genvar gi;")
    a("generate")
    a("    for (gi = 0; gi < PAD; gi = gi + 1) begin : g_decay")
    a("        assign decayed[gi] = (v[gi] * DECAY_NUM) >>> DECAY_SHIFT;")
    a("    end")
    a("endgenerate")
    a("")
    a("// sign-extended weight column contribution")
    a("wire signed [ACC_W-1:0] col_part [0:PAD-1];")
    a("generate")
    a("    for (gi = 0; gi < PAD; gi = gi + 1) begin : g_acc")
    a(f"        assign col_part[gi] = col_bit ? $signed({{ {{ (ACC_W-WW){{ col[gi*WW + WW-1] }} }}, col[gi*WW +: WW] }}) : $signed({{ACC_W{{1'b0}}}});")
    a("    end")
    a("endgenerate")
    a("")
    a("reg [PAD-1:0] fires;")
    a("reg [PAD-1:0] emit_tmp;")
    a("reg found;")
    a("reg signed [31:0] v_cand;")
    a("integer i;")
    a("always @(posedge clk) begin")
    a("    if (!rst_n) begin")
    a("        phase <= PH_IDLE;")
    a("        fire_shift <= {PAD{1'b0}};")
    a("        for (i = 0; i < PAD; i = i + 1) begin")
    a("            v[i] <= ACC_W_REST;")
    a("            acc[i] <= {ACC_W{1'b0}};")
    a("        end")
    a("        spike_out_valid <= 1'b0;")
    a("        spike_out_addr <= 16'd0;")
    a("        spike_out_data <= 1'b0;")
    a("        col_bit <= 1'b0;")
    a("    end else begin")
    a("        spike_out_valid <= 1'b0;")
    a("        case (phase)")
    a("            PH_IDLE: begin")
    a("                if (inject_valid) begin")
    a("                    col <= rom_word(inject_addr);")
    a("                    col_bit <= inject_data;")
    a("                    phase <= PH_INJECT;")
    a("                end")
    a("            end")
    a("            PH_INJECT: begin")
    a("                for (i = 0; i < PAD; i = i + 1)")
    a("                    acc[i] <= acc[i] + col_part[i];")
    a("                if (inject_valid) begin")
    a("                    col <= rom_word(inject_addr);")
    a("                    col_bit <= inject_data;")
    a("                end else begin")
    a("                    phase <= PH_UPDATE;")
    a("                end")
    a("            end")
    a("            PH_UPDATE: begin")
    a("                fires = {PAD{1'b0}};")
    a("                for (i = 0; i < PAD; i = i + 1) begin")
    a("                    v_cand = decayed[i] + acc[i] - ACC_W_LEAK;")
    a("                    if (v_cand >= ACC_W_THR) begin")
    a("                        fires[i] = 1'b1;")
    a("                        v[i] <= ACC_W_REST;")
    a("                    end else begin")
    a("                        v[i] <= v_cand[ACC_W-1:0];")
    a("                    end")
    a("                    acc[i] <= {ACC_W{1'b0}};")
    a("                end")
    a("                fire_shift <= fires;")
    a("                phase <= PH_EMIT;")
    a("            end")
    a("            PH_EMIT: begin")
    a("                emit_tmp = fire_shift;")
    a("                found = 1'b0;")
    a("                for (i = 0; i < PAD; i = i + 1) begin")
    a("                    if (!found && emit_tmp[i]) begin")
    a("                        found = 1'b1;")
    a("                        spike_out_addr <= i;")
    a("                        spike_out_data <= 1'b1;")
    a("                        spike_out_valid <= 1'b1;")
    a("                        emit_tmp[i] = 1'b0;")
    a("                    end")
    a("                end")
    a("                fire_shift <= emit_tmp;")
    a("                if (emit_tmp == {PAD{1'b0}}) phase <= PH_IDLE;")
    a("            end")
    a("        endcase")
    a("    end")
    a("end")
    a("")
    a("// weights as constant case tree: survives Yosys synthesis (initial-block")
    a("// ROMs become flops with dropped init on sky130 — see peer ruling T5)")
    a("function [PAD*WW-1:0] rom_word;")
    a("    input [15:0] a;")
    a("    begin")
    a("        case (a)")
    for s in range(p):
        a(f"            16'd{s}: rom_word = {p * ww}'h{rom_words[s]:0{(p * ww + 3) // 4}x};")
    a("            default: rom_word = {(PAD*WW){1'b0}};")
    a("        endcase")
    a("    end")
    a("endfunction")
    a("endmodule")
    return "\n".join(L) + "\n"