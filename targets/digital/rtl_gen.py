"""Parameterized LIF fabric RTL generator — OpenSpike-compatible memory interface.

Weights are EXTERNAL (docs/openspike-memory-interface.md): the fabric holds
no weight memory. A synchronous SRAM supplies one PAD*WW-bit weight word per
source; word[s] bit slice [i*WW +: WW] is the signed weight from source s
onto neuron i (golden model: weight_words()). Port protocol, no handshake:
the address is a registered output and the data for the address visible in
cycle N is on w_read_sram in cycle N+1. Fixed latency — any memory with a
different latency breaks the design silently.

Protocol (one timestep):
- Host drives in_spk[N-1:0] = injected spike frame and pulses timestep_start.
  The FSM latches both, then streams all PAD weight words itself: in cycle s
  it adds word s (gated by in_spk[s]) into the PAD accumulators, one word per
  cycle. Cycle count per timestep is PAD + O(1) and independent of spike rate.
- UPDATE: v' = (decay*v >>> shift) + acc - leak; fire when v' >= THR, reset
  fired neurons to REST.
- EMIT: fires stream out one per cycle on spike_out_valid/spike_out_addr
  until none remain.

cfg["weight_store"] = "rom" (dense-ROM baseline, #2) keeps the same FSM and
moves the SRAM inside: the weight_words() image becomes a constant case tree
with a registered read, so the N -> N+1 latency is unchanged. The module name
gets a _rom suffix so its ORFS results never mix with the external design.
"""

PH_IDLE = 0
PH_RUN = 1
PH_UPDATE = 2
PH_EMIT = 3


def _next_pow2(n: int) -> int:
    p = 2
    while p < n:
        p *= 2
    return p


def module_name(cfg: dict) -> str:
    suffix = "_rom" if _rom(cfg) else ""
    return f"snn_core_{cfg['neurons']}{suffix}"


def _rom(cfg: dict) -> bool:
    return cfg.get("weight_store", "external") == "rom"


def pad_size(cfg: dict) -> int:
    return _next_pow2(max(int(cfg["neurons"]), 2))


def addr_width(cfg: dict) -> int:
    return pad_size(cfg).bit_length()


def generate_rtl(cfg: dict) -> str:
    n = int(cfg["neurons"])
    ww = int(cfg["weight_width"])
    p = pad_size(cfg)
    aw = addr_width(cfg)
    acc_w = ww + p.bit_length() + 4  # signed headroom for decayed+acc
    thr = int(round(float(cfg.get("threshold", 1.0)) * 2**ww))
    rest = int(round(float(cfg.get("rest", 0.0)) * 2**ww))
    leak = int(round(float(cfg.get("leak", 0.0)) * 2**ww))

    L: list[str] = []
    a = L.append
    a(f"// generated by rtl_gen.py; neurons={n} fanout={cfg.get('fanout')} ww={ww} seed={cfg.get('seed', 1)}")
    a("// weights live in external SRAM (OpenSpike interface): fabric has none")
    a("`timescale 1ns/1ps")
    a(f"module {module_name(cfg)} (")
    a("    input  wire        clk,")
    a("    input  wire        rst_n,")
    a("    input  wire        timestep_start,")
    a(f"    input  wire [{n}-1:0] in_spk,")
    if not _rom(cfg):
        a(f"    input  wire [{p * ww}-1:0] w_read_sram,")
        a(f"    output reg  [{aw}-1:0] w_read_sram_addr,")
    a("    output reg         spike_out_valid,")
    a("    output reg  [15:0] spike_out_addr,")
    a("    output reg         spike_out_data")
    a(");")
    a(f"localparam N = {n};")
    a(f"localparam PAD = {p};")
    a(f"localparam AW = {aw};")
    a(f"localparam WW = {ww};")
    a(f"localparam ACC_W = {acc_w};")
    a(f"localparam signed ACC_W_THR = {acc_w}'sd{thr};")
    a(f"localparam signed ACC_W_REST = {acc_w}'sd{rest};")
    a(f"localparam signed ACC_W_LEAK = {acc_w}'sd{leak};")
    a("localparam signed DECAY_NUM = 14;")
    a("localparam DECAY_SHIFT = 4;")
    a(f"localparam PH_IDLE = {PH_IDLE}, PH_RUN = {PH_RUN},")
    a(f"          PH_UPDATE = {PH_UPDATE}, PH_EMIT = {PH_EMIT};")
    a("")
    a("reg [1:0] phase;")
    a(f"reg signed [ACC_W-1:0] v [0:PAD-1];")
    a(f"reg signed [ACC_W-1:0] acc [0:PAD-1];")
    a(f"reg [PAD-1:0] fire_shift;")
    a(f"reg [PAD-1:0] in_spk_buf;")
    a(f"reg [{aw}:0] scnt;  // counts PAD too, one extra bit")
    if _rom(cfg):
        # weights as constant case tree: survives Yosys synthesis (initial-block
        # ROMs become flops with dropped init on sky130, see 079bfaf)
        from targets.digital.model import weight_words
        a(f"reg [{aw}-1:0] w_read_sram_addr;")
        a(f"reg [{p * ww}-1:0] w_read_sram;")
        a(f"function [{p * ww}-1:0] rom_word;")
        a(f"    input [{aw}-1:0] ra;")
        a("    begin")
        a("        case (ra)")
        for s, w in enumerate(weight_words(cfg)):
            a(f"            {aw}'d{s}: rom_word = {p * ww}'h{w:0{(p * ww + 3) // 4}x};")
        a(f"            default: rom_word = {{{p * ww}{{1'b0}}}};")
        a("        endcase")
        a("    end")
        a("endfunction")
        a("// registered read: addr in cycle N, data in N+1, as the external SRAM")
        a("always @(posedge clk) w_read_sram <= rom_word(w_read_sram_addr);")
    a("")
    a("// decayed membrane, 32-bit intermediate, no truncation before compare")
    a("wire signed [31:0] decayed [0:PAD-1];")
    a("genvar gi;")
    a("generate")
    a("    for (gi = 0; gi < PAD; gi = gi + 1) begin : g_decay")
    a("        assign decayed[gi] = (v[gi] * DECAY_NUM) >>> DECAY_SHIFT;")
    a("    end")
    a("endgenerate")
    a("")
    a("// sign-extended weight word straight off the SRAM bus, one word per cycle")
    a("wire signed [ACC_W-1:0] col_part [0:PAD-1];")
    a("generate")
    a("    for (gi = 0; gi < PAD; gi = gi + 1) begin : g_acc")
    a(f"        assign col_part[gi] = $signed({{ {{ (ACC_W-WW){{ w_read_sram[gi*WW + WW-1] }} }}, w_read_sram[gi*WW +: WW] }});")
    a("    end")
    a("endgenerate")
    a("// word currently on the bus + its input spike gate")
    a("wire [AW-1:0] s_word = scnt - 1'b1;")
    a("wire spk_gate = (scnt != 0) && in_spk_buf[s_word];")
    a("")
    a("reg [PAD-1:0] fires;")
    a("reg [PAD-1:0] emit_tmp;")
    a("reg found;")
    a("reg signed [31:0] v_cand;")
    a("integer i;")
    a("always @(posedge clk) begin")
    a("    if (!rst_n) begin")
    a("        phase <= PH_IDLE;")
    a("        fire_shift <= {PAD{1'b0}};")
    a("        w_read_sram_addr <= {AW{1'b0}};")
    a("        scnt <= {(AW+1){1'b0}};")
    a("        for (i = 0; i < PAD; i = i + 1) begin")
    a("            v[i] <= ACC_W_REST;")
    a("            acc[i] <= {ACC_W{1'b0}};")
    a("        end")
    a("        spike_out_valid <= 1'b0;")
    a("        spike_out_addr <= 16'd0;")
    a("        spike_out_data <= 1'b0;")
    a("    end else begin")
    a("        spike_out_valid <= 1'b0;")
    a("        case (phase)")
    a("            PH_IDLE: begin")
    a("                if (timestep_start) begin")
    a("                    in_spk_buf <= " + ("in_spk;" if p == n else f"{{{{(PAD-N){{1'b0}}}}, in_spk}};"))
    a("                    w_read_sram_addr <= {AW{1'b0}};")
    a("                    scnt <= {(AW+1){1'b0}};")
    a("                    phase <= PH_RUN;")
    a("                end")
    a("            end")
    a("            PH_RUN: begin")
    a("                // word (scnt-1) is on the bus this cycle (addr in N, data in N+1)")
    a("                for (i = 0; i < PAD; i = i + 1)")
    a("                    acc[i] <= acc[i] + (spk_gate ? col_part[i] : {ACC_W{1'b0}});")
    a("                if (scnt + 1 < PAD)")
    a("                    w_read_sram_addr <= scnt + 1'b1;")
    a("                scnt <= scnt + 1'b1;")
    a("                if (scnt == PAD) phase <= PH_UPDATE;  // last word (PAD-1) consumed")
    a("            end")
    a("            PH_UPDATE: begin")
    a("                fires = {PAD{1'b0}};")
    a("                for (i = 0; i < PAD; i = i + 1) begin")
    a("                    v_cand = decayed[i] + acc[i] - ACC_W_LEAK;")
    a("                    if (v_cand >= ACC_W_THR) begin")
    a("                        fires[i] = 1'b1;")
    a("                        v[i] <= ACC_W_REST;")
    a("                    end else begin")
    a("                        v[i] <= v_cand[ACC_W-1:0];")
    a("                    end")
    a("                    acc[i] <= {ACC_W{1'b0}};")
    a("                end")
    a("                fire_shift <= fires;")
    a("                phase <= PH_EMIT;")
    a("            end")
    a("            PH_EMIT: begin")
    a("                emit_tmp = fire_shift;")
    a("                found = 1'b0;")
    a("                for (i = 0; i < PAD; i = i + 1) begin")
    a("                    if (!found && emit_tmp[i]) begin")
    a("                        found = 1'b1;")
    a("                        spike_out_addr <= i;")
    a("                        spike_out_data <= 1'b1;")
    a("                        spike_out_valid <= 1'b1;")
    a("                        emit_tmp[i] = 1'b0;")
    a("                    end")
    a("                end")
    a("                fire_shift <= emit_tmp;")
    a("                if (emit_tmp == {PAD{1'b0}}) phase <= PH_IDLE;")
    a("            end")
    a("        endcase")
    a("    end")
    a("end")
    a("endmodule")
    return "\n".join(L) + "\n"